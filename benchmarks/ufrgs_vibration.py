"""Benchmark: can a hotend accelerometer tell a restricted nozzle from healthy and other faults?

Data: UFRGS vibration dataset (Zenodo 22716165, CC BY 4.0), converted to 10 Hz runs with
``accel_rms`` and four band energies. Windows of the 10 Hz table are summarised into features and
classified with a gradient-boosted tree model (or a random forest), evaluated by
leave-one-print-out cross-validation (grouped by run, never by window).

    python -m benchmarks.ufrgs_vibration                 # real data in data/open/ufrgs_vibration
    python -m benchmarks.ufrgs_vibration --fixture       # synthetic fixture, pipeline check only

Results: ``benchmarks/results/ufrgs_vibration.md`` (real) or ``..._FIXTURE.md`` (synthetic).
"""

from __future__ import annotations

import argparse
import sys
import tempfile
from dataclasses import dataclass
from datetime import UTC, datetime
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.ensemble import HistGradientBoostingClassifier, RandomForestClassifier
from sklearn.metrics import confusion_matrix, precision_recall_fscore_support
from sklearn.model_selection import LeaveOneGroupOut

from clogguard.core.schema import BASE_RATE_HZ, Run
from clogguard.datasets import ufrgs
from clogguard.datasets.accel import ACCEL_COLUMNS, BAND_COLUMNS
from clogguard.datasets.registry import REGISTRY, UFRGS_LABELS

CLASSES = list(UFRGS_LABELS)  # healthy, temp_220, temp_230, loose_head, nozzle_03, nozzle_02
GROUP_OF = {
    "healthy": "healthy",
    "nozzle_03": "restricted",
    "nozzle_02": "restricted",
    "temp_220": "other_fault",
    "temp_230": "other_fault",
    "loose_head": "other_fault",
}
REAL_HEADER = "Data source: open dataset (UFRGS, CC BY 4.0) - not ClogGuard hardware"
FIXTURE_HEADER = (
    "Data source: SYNTHETIC fixture generated by `--fixture` - not the UFRGS dataset and not "
    "ClogGuard hardware. These numbers only show that the pipeline runs end to end."
)
EPS = 1e-12


# ---------------------------------------------------------------- features


def window_features(run: Run, window_s: float = 5.0, step_s: float = 2.5) -> pd.DataFrame:
    """Summarise the 10 Hz accel table in sliding windows (past data only inside each window)."""
    f = run.frame
    w = round(window_s * BASE_RATE_HZ)
    s = max(1, round(step_s * BASE_RATE_HZ))
    if len(f) < w:
        return pd.DataFrame()
    log = np.log10(f[list(ACCEL_COLUMNS)].to_numpy(dtype=float) + EPS)
    bands = f[list(BAND_COLUMNS)].to_numpy(dtype=float)
    frac = bands / (np.nansum(bands, axis=1, keepdims=True) + EPS)
    rows = []
    for start in range(0, len(f) - w + 1, s):
        sl = slice(start, start + w)
        lw, fw = log[sl], frac[sl]
        row: dict[str, float] = {"t_end": float(f["t"].iloc[start + w - 1])}
        for j, c in enumerate(ACCEL_COLUMNS):
            row[f"{c}_logmean"] = float(np.nanmean(lw[:, j]))
            row[f"{c}_logstd"] = float(np.nanstd(lw[:, j]))
            row[f"{c}_logp90"] = float(np.nanpercentile(lw[:, j], 90))
        for j, c in enumerate(BAND_COLUMNS):
            row[f"{c}_frac"] = float(np.nanmean(fw[:, j]))
        rows.append(row)
    return pd.DataFrame(rows)


def build_dataset(
    runs: list[Run], window_s: float, step_s: float
) -> tuple[pd.DataFrame, np.ndarray, np.ndarray]:
    parts, labels, groups = [], [], []
    for r in runs:
        wf = window_features(r, window_s, step_s)
        if wf.empty:
            continue
        parts.append(wf)
        labels += [ufrgs.fault_label(r.meta)] * len(wf)
        groups += [r.run_id] * len(wf)
    if not parts:
        raise ValueError("no windows: runs are shorter than one window")
    X = pd.concat(parts, ignore_index=True).drop(columns=["t_end"])
    return X, np.array(labels), np.array(groups)


# ---------------------------------------------------------------- evaluation


@dataclass
class Result:
    classes: list[str]
    y_true: np.ndarray
    y_pred: np.ndarray
    groups: np.ndarray
    n_prints: int
    model: str


def make_model(kind: str, seed: int) -> HistGradientBoostingClassifier | RandomForestClassifier:
    if kind == "rf":
        return RandomForestClassifier(n_estimators=200, n_jobs=2, random_state=seed)
    return HistGradientBoostingClassifier(max_iter=150, learning_rate=0.1, random_state=seed)


def leave_one_print_out(
    X: pd.DataFrame, y: np.ndarray, groups: np.ndarray, kind: str = "hgb", seed: int = 0
) -> Result:
    pred = np.empty_like(y)
    for train, test in LeaveOneGroupOut().split(X, y, groups):
        model = make_model(kind, seed)
        model.fit(X.iloc[train], y[train])
        pred[test] = model.predict(X.iloc[test])
    present = [c for c in CLASSES if c in set(y)]
    return Result(present, y, pred, groups, len(set(groups)), kind)


def _md_table(header: list[str], rows: list[list[str]]) -> list[str]:
    out = ["| " + " | ".join(header) + " |", "| " + " | ".join("---" for _ in header) + " |"]
    out += ["| " + " | ".join(r) + " |" for r in rows]
    return out


def _confusion_md(y: np.ndarray, p: np.ndarray, classes: list[str]) -> list[str]:
    cm = confusion_matrix(y, p, labels=classes)
    rows = [[f"**{c}**", *(str(v) for v in cm[i])] for i, c in enumerate(classes)]
    return _md_table(["true \\ predicted", *classes], rows)


def _metrics_md(y: np.ndarray, p: np.ndarray, classes: list[str]) -> list[str]:
    pr, rc, f1, sup = precision_recall_fscore_support(y, p, labels=classes, zero_division=0)
    rows = [
        [c, f"{pr[i]:.2f}", f"{rc[i]:.2f}", f"{f1[i]:.2f}", str(int(sup[i]))]
        for i, c in enumerate(classes)
    ]
    return _md_table(["class", "precision", "recall", "F1", "windows"], rows)


def print_level(res: Result) -> pd.DataFrame:
    """Majority vote of window predictions per print."""
    df = pd.DataFrame({"g": res.groups, "y": res.y_true, "p": res.y_pred})
    agg = df.groupby("g").agg(
        y=("y", "first"),
        p=("p", lambda s: s.value_counts().idxmax()),
        windows=("p", "size"),
        share=("p", lambda s: float(s.value_counts(normalize=True).iloc[0])),
    )
    return agg.reset_index()


def render_markdown(res: Result, fixture: bool, window_s: float, step_s: float) -> str:
    info = REGISTRY["ufrgs_vibration"]
    acc = float(np.mean(res.y_true == res.y_pred))
    pl = print_level(res)
    g_true = np.array([GROUP_OF[v] for v in res.y_true])
    g_pred = np.array([GROUP_OF[v] for v in res.y_pred])
    groups = [g for g in ("healthy", "restricted", "other_fault") if g in set(g_true)]
    lines = [
        "# UFRGS vibration benchmark" + (" (SYNTHETIC FIXTURE)" if fixture else ""),
        "",
        FIXTURE_HEADER if fixture else REAL_HEADER,
        "",
    ]
    if not fixture:
        lines += [f"Citation: {info.citation}", ""]
    lines += [
        "Question: can a hotend accelerometer tell a restricted nozzle from a healthy printer "
        "and from other faults?",
        "",
        f"- Generated: {datetime.now(UTC).isoformat(timespec='seconds')}",
        f"- Prints: {res.n_prints}; windows: {len(res.y_true)} ({window_s:g} s, step "
        f"{step_s:g} s, from 10 Hz accel_rms and band energies)",
        f"- Model: {'random forest' if res.model == 'rf' else 'HistGradientBoosting'}; "
        "leave-one-print-out cross-validation (split by print, never by window)",
        f"- Window accuracy: {acc:.3f}; print-level accuracy (majority vote): "
        f"{float(np.mean(pl['y'] == pl['p'])):.3f}",
        "- Windows within a print are correlated; the print count, not the window count, is "
        "the effective sample size.",
        "",
        "## Confusion matrix (windows, six classes)",
        "",
        *_confusion_md(res.y_true, res.y_pred, res.classes),
        "",
        "## Per-class metrics (windows)",
        "",
        *_metrics_md(res.y_true, res.y_pred, res.classes),
        "",
        "## Grouped: healthy vs restricted nozzle vs other fault",
        "",
        *_confusion_md(g_true, g_pred, groups),
        "",
        *_metrics_md(g_true, g_pred, groups),
        "",
        "## Per print (majority vote)",
        "",
        *_md_table(
            ["print", "true", "predicted", "windows", "vote share"],
            [[r.g, r.y, r.p, str(r.windows), f"{r.share:.2f}"] for r in pl.itertuples(index=False)],
        ),
        "",
    ]
    return "\n".join(lines)


# ---------------------------------------------------------------- synthetic fixture


def make_fixture(
    root: str | Path, n_per_class: int = 3, seconds: float = 12.0, seed: int = 0
) -> list[Path]:
    """Write synthetic 3200 Hz UFRGS-style parquet files. Class signatures are invented."""
    rng = np.random.default_rng(seed)
    root = Path(root)
    root.mkdir(parents=True, exist_ok=True)
    fs = ufrgs.NOMINAL_FS_HZ
    # (frequency Hz, amplitude g) added per class: invented, only to exercise the pipeline.
    signature = {
        "healthy": [],
        "temp_220": [(70.0, 0.04)],
        "temp_230": [(70.0, 0.09)],
        "loose_head": [(18.0, 0.25), (36.0, 0.12)],
        "nozzle_03": [(950.0, 0.06)],
        "nozzle_02": [(950.0, 0.12), (420.0, 0.05)],
    }
    paths: list[Path] = []
    pid = 1
    for label in CLASSES:
        for k in range(n_per_class):
            two = label == "healthy" and k == 0  # one two-print file, like benchy_11_12
            segs = 2 if two else 1
            t_parts, a_parts = [], []
            t0 = 0.0
            for _ in range(segs):
                t = t0 + np.arange(0, seconds, 1 / fs)
                gain = rng.uniform(0.8, 1.2)
                env = 1 + 0.3 * np.sin(2 * np.pi * rng.uniform(0.05, 0.2) * t)
                axes = []
                for _axis in range(3):
                    x = 0.05 * gain * rng.standard_normal(t.size)
                    for f0 in (120.0, 240.0, 310.0):  # stepper/motion tones
                        x += gain * 0.08 * env * np.sin(2 * np.pi * f0 * t + rng.uniform(0, 6))
                    for f0, amp in signature[label]:
                        x += (
                            amp
                            * rng.uniform(0.7, 1.3)
                            * np.sin(2 * np.pi * f0 * t + rng.uniform(0, 6))
                        )
                    axes.append(x)
                axes[2] = axes[2] + 1.0  # gravity on z
                t_parts.append(t)
                a_parts.append(np.column_stack(axes))
                t0 = t[-1] + 30.0  # 30 s gap between two prints in one file
            t_all = np.concatenate(t_parts)
            a_all = np.vstack(a_parts)
            ids = f"{pid}_{pid + 1}" if two else f"{pid}"
            pid += segs
            stamp = f"08_0{1 + (pid % 4)}_{10 + (pid % 12):02d}_{pid % 60:02d}_00"
            p = root / f"benchy_{ids}_{label}_{stamp}.parquet"
            pd.DataFrame(
                {
                    "timestamp_us": (t_all * 1e6).astype("int64"),
                    "x": a_all[:, 0].astype("float32"),
                    "y": a_all[:, 1].astype("float32"),
                    "z": a_all[:, 2].astype("float32"),
                }
            ).to_parquet(p, index=False)
            paths.append(p)
    return paths


# ---------------------------------------------------------------- CLI


def run(
    data_dir: Path,
    out_path: Path,
    fixture: bool,
    window_s: float,
    step_s: float,
    kind: str,
    seed: int,
    limit: int | None = None,
) -> Result:
    runs = ufrgs.load_dir(data_dir, limit=limit)
    if not runs:
        raise FileNotFoundError(
            f"no UFRGS files in {data_dir}; run `clogguard data download ufrgs_vibration` first"
        )
    X, y, g = build_dataset(runs, window_s, step_s)
    res = leave_one_print_out(X, y, g, kind=kind, seed=seed)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(render_markdown(res, fixture, window_s, step_s), encoding="utf-8")
    return res


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--data-dir", type=Path, default=Path("data/open/ufrgs_vibration"))
    ap.add_argument("--out-dir", type=Path, default=Path(__file__).parent / "results")
    ap.add_argument("--fixture", action="store_true", help="use a synthetic fixture instead")
    ap.add_argument("--window-s", type=float, default=5.0)
    ap.add_argument("--step-s", type=float, default=2.5)
    ap.add_argument("--model", choices=["hgb", "rf"], default="hgb")
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--limit", type=int, default=None, help="use at most N files")
    ap.add_argument("--fixture-per-class", type=int, default=3, help="synthetic prints per class")
    ap.add_argument("--fixture-seconds", type=float, default=12.0, help="synthetic print length")
    ns = ap.parse_args(sys.argv[1:] if argv is None else argv)
    if ns.fixture:
        out = ns.out_dir / "ufrgs_vibration_FIXTURE.md"
        with tempfile.TemporaryDirectory() as tmp:
            make_fixture(tmp, ns.fixture_per_class, ns.fixture_seconds, seed=ns.seed)
            res = run(Path(tmp), out, True, ns.window_s, ns.step_s, ns.model, ns.seed)
    else:
        out = ns.out_dir / "ufrgs_vibration.md"
        res = run(ns.data_dir, out, False, ns.window_s, ns.step_s, ns.model, ns.seed, ns.limit)
    acc = float(np.mean(res.y_true == res.y_pred))
    print(f"{res.n_prints} prints, window accuracy {acc:.3f} -> {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
